/* 접수번호 : YYYYMMDD + 일련 3자리 = 11자리.
   앞뒤에 숫자가 붙어 있으면 매치하지 않는다. 자릿수를 잘못 적은 12자리 오타
   (예: 202508050019)에서 앞 11자리만 잘라 "엉뚱한 건"으로 연결하는 사고를 막기 위함이다.
   실측상 그런 오타는 소수라, 억지로 추측하느니 안 잡는 쪽이 안전하다. */
var CKW_RX_ASNO = /(?:^|[^0-9])(20\d{9})(?![0-9])/g;

/* 전화번호/내선. 접수번호는 '2'로 시작하므로 '0' 시작 조건만으로 겹치지 않는다. */
var CKW_RX_TEL  = /(?:^|[^0-9])(0\d{1,2}[-\s]?\d{3,4}[-\s]?\d{4})(?![0-9])/g;

/* 환자 식별 : 이름(등록번호) */
var CKW_RX_PAT  = /([가-힣]{2,4})\s*\(\s*(\d{4,10})\s*\)/g;

/* 버전.
   ★ 날짜(2025.11.11)와 반드시 구분해야 한다. 챗봇 템플릿의 「발생일시」가 같은 모양이라
     느슨하게 잡으면 전 건의 30% 이상이 '버전' 칩으로 잘못 뜬다.
   ① 4자리.3~4자리 : 월은 3~4자리가 될 수 없으므로 날짜와 절대 안 겹친다
                     (2025.1027.2 / 2025.801 / 0905.1130 — 실제 등장 형태)
   ②~④ 그 외 모양은 ver / 버전 마커가 본문에 명시된 경우에만 인정한다. */
var CKW_RX_VER = [
	/(?:^|[^0-9.])(\d{4}\.\d{3,4}(?:\.\d+)?)(?![0-9])/g,
	/(?:ver|VER|Ver)\s*[.:：]?\s*(\d[\d.]{1,14}\d)/g,
	/(?:^|[^0-9])(\d{3,4})\s*버\s*[전젼]/g,
	/(?:^|[^0-9])(20\d{6})\s*버\s*[전젼]/g
];

/* 오류코드.
   ★ '코드'라는 말이 반드시 있어야 한다. 「오류 2025년…」 같은 문장에서 연도를 오류코드로
     잡는 사고를 막기 위해 '코?드?' 처럼 optional 로 두지 않는다. */
var CKW_RX_ERR = [
	/(?:오류|에러)\s*코드\s*[:：]?\s*(-?\d{3,10})/g,
	/(?:^|[^0-9-])(-?\d{9,10})\s*(?:오류|에러)/g,
	/error\s*code\s*[:：]?\s*([A-Za-z0-9._-]{3,40})/gi
];

/* 템플릿 필드값 파싱. 「1. 프로그램명 : 청구심사    2. 화면명 : …」 처럼 한 줄에 여러 라벨이
   이어 붙는 경우가 많아, 반드시 "다음 라벨 직전"에서 끊어야 한다.
   (이 처리를 빼면 프로그램명 값으로 "2. 화면명 :" 이 통째로 잡힌다 — 실제로 3,209건)
   공백 4칸 이상도 끊는 지점에 넣는다. 템플릿이 한 줄로 눌려 들어올 때 필드 사이 간격이다. */
var CKW_FLD_NEXT = '(?=\\s*\\d\\s*[.．]?\\s*(?:챗봇요약|프로그램명|화면명|환자등록번호|발생일시|내용)\\s*[:：]|\\s{4,}|[\\r\\n]|$)';
/* 값이 아니라 "안 적었다"는 뜻인 문구들 */
var CKW_FLD_NOISE = {'':1,'-':1,'다수':1,'없음':1,'전체':1,'모든환자':1,'모든 환자':1,'해당사항 없음':1,
                     '해당없음':1,'금일':1,'오늘':1,'미상':1,'.':1,'ㅇ':1};

function ckw_field(text, label){
	var rx = new RegExp(label + '\\s*[:：]\\s*([\\s\\S]{0,80}?)' + CKW_FLD_NEXT);
	var m = rx.exec(String(ckw_nvl(text,'')));
	if(!m) return '';
	var v = String(m[1]).replace(/^[\s.．]+|[\s.．]+$/g, '');
	if(CKW_FLD_NOISE[v]) return '';
	if(v.length < 2) return '';
	return v;
}

