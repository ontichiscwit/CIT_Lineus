function ckw_toggle(i){
	var c = ckw.chips[i];
	if(!c) return;
	/* 과거 이력에 0건인 칩은 눌러 봐야 빈 목록이다. 누르지 못하게 막아 두었지만
	   (ckw_chipsHtml 의 disabled) 혹시 모를 경로를 위해 여기서도 막는다. */
	if(ckw.state === 'done' && c.hit === 0 && !ckw.sel[c.key]) return;
	ckw.sel[c.key] = !ckw.sel[c.key];
	if(ckw.state === 'done' || ckw.state === 'empty'){
		ckw_rescore();
		ckw.state = 'done';
	}
	ckw_render();
}
function ckw_clear(){
	ckw.sel = {};
	if(ckw.docs.length){ ckw_rescore(); ckw.state = 'done'; }
	ckw_render();
}

