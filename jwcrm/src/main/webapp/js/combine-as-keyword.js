/**
 * 현재 상세(caws.*)를 기준으로 키워드를 뽑고 연관 이력을 조회한다.
 * @param force true 면 같은 건이어도 다시 조회한다(오류 후 재시도).
 */
function ckw_run(force){
	if(typeof caws === 'undefined' || !caws) return;
	if(!document.querySelector('#asRecord .caws-past')) return;	/* 과거이력 패널이 없으면 아무것도 안 한다 */

	var row = caws.row || {}, vo = caws.vo || {};
	var custCode = ckw_nvl(row.cust_code, ckw_nvl(vo.cust_code,''));

	ckw.asNo     = ckw_nvl(caws.asNo,'');
	ckw.custCode = custCode;
	ckw.sel      = {};
	ckw.docs     = [];
	ckw.ranked   = [];
	ckw.refs     = [];

	ckw_empLoad();					/* 직원 명단(담당자 칩용). 없으면 담당자 칩만 빠진다 */
	ckw.chips = ckw_extract();

	if(custCode === ''){
		ckw.state = 'nocust';
		ckw_render();
		return;
	}

	ckw.state = 'loading';
	ckw_render();					/* 칩은 즉시 보여주고, 목록만 나중에 채운다 */
	ckw_fetch(custCode, ++ckw.seq);
	if(force){ /* 인자 사용 표시용 — 위에서 이미 seq 를 올려 항상 재조회된다 */ }
}

/* 조회 없이 화면만 다시 그린다 (caws_renderRecord 로 #asRecord 가 날아갔을 때). */
function ckw_remount(){
	if(ckw.asNo === '' || ckw.asNo !== ckw_nvl(caws.asNo,'')) return;	/* 다른 건이면 건드리지 않는다 */
	if(ckw.state === 'idle') return;
	ckw_render();
}

/* =============================================================================
 * 8) 기존 함수 래핑 (combine-as-thread.js 무수정)
 * -----------------------------------------------------------------------------
 * caws_renderAll() 은 caws_renderRecord() → caws_pastReset() 순으로 호출한다.
 *   - caws_pastReset  : 건이 바뀔 때마다 1회. 여기서 키워드 추출 + 연관 이력 조회를 건다.
 *   - caws_renderRecord: 인라인 편집 저장 등으로 #asRecord 만 다시 그릴 때도 호출된다.
 *                        이때 우리 블록이 통째로 지워지므로 "조회 없이" 다시 꽂아준다.
 * setTimeout(0) 으로 미루는 이유: 원본이 DOM 을 다 그린 뒤에 붙어야 .caws-past 를 찾을 수 있고,
 * 원본 흐름에 예외가 섞여 들어가지 않는다.
 * ========================================================================== */
(function(){
	if(typeof window.caws_pastReset !== 'function'){
		/* combine-as-thread.js 가 없으면(캐시/배포 누락) 아무 일도 하지 않는다 */
		return;
	}

	var _pastReset = window.caws_pastReset;
	window.caws_pastReset = function(){
		var r = _pastReset.apply(this, arguments);
		try{ setTimeout(function(){ ckw_run(); }, 0); }catch(e){}
		return r;
	};

	if(typeof window.caws_renderRecord === 'function'){
		var _renderRecord = window.caws_renderRecord;
		window.caws_renderRecord = function(){
			var r = _renderRecord.apply(this, arguments);
			try{ setTimeout(function(){ ckw_remount(); }, 0); }catch(e){}
			return r;
		};
	}
})();
