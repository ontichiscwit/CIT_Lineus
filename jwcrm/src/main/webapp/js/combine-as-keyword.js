/* #asRecord 안 과거이력(.caws-past) 바로 "위"에 블록을 끼운다.
   caws_renderRecord() 가 #asRecord 를 통째로 다시 그리므로, 그릴 때마다 다시 꽂아야 한다. */
function ckw_mount(){
	var past = document.querySelector('#asRecord .caws-past');
	if(!past) return null;
	var box = ckw_el('ckwBox');
	if(box && box.parentNode === past.parentNode) return box;

	box = document.createElement('div');
	box.id = 'ckwBox';
	box.className = 'ckw-box';
	past.parentNode.insertBefore(box, past);
	return box;
}

function ckw_kindNm(k){
	return { asno:'접수번호', tel:'연락처', prog:'프로그램', screen:'화면',
	         patient:'환자', ver:'버전', err:'오류코드', emp:'담당자',
	         sym:'증상', term:'키워드' }[k] || '키워드';
}

/* 상담원이 확인하는 순서(어디서 → 무슨 문제 → 식별 → 그 외)대로 줄을 나눠 그린다.
   예전에는 한 줄에 평평하게 늘어놔서, "마약류통합정보조회" 와 "것처럼" 이 같은
   무게로 보였다. 무엇을 먼저 봐야 하는지가 화면에 드러나야 한다. */
function ckw_chipsHtml(){
	/* "그 외 키워드" 줄을 걷어낸 뒤로는 칩이 하나도 없는 경우가 27.6% 다(표본 6,000건).
	   드문 사고가 아니라 흔한 정상 상태라는 뜻이다. 고시·공지처럼 프로그램도 증상도
	   없는 문의가 실제로 그만큼 있다. 그래서 "없습니다" 로 끝내면 안 된다.
	   아래 연관 이력은 칩과 무관하게 본문 전체로 찾으므로, 그 점을 같이 적어 준다. */
	if(!ckw.chips.length){
		return '<div class="ckw-none">문의 내용에서 프로그램·증상을 찾지 못했습니다.'
		     + ' 아래 연관 이력은 본문 전체를 기준으로 찾았습니다.</div>';
	}
	var order = [], i;
	for(i=0; i<ckw.chips.length; i++) order.push(i);
	order.sort(function(a, b){
		if(ckw.chips[a].g !== ckw.chips[b].g) return ckw.chips[a].g - ckw.chips[b].g;
		return a - b;			/* 같은 줄 안에서는 원래 순서 유지 */
	});

	var s = '', gNow = 0, n;
	for(n=0; n<order.length; n++){
		i = order[n];
		var c = ckw.chips[i];
		if(c.g !== gNow){
			if(gNow !== 0) s += '</div>';
			s += '<div class="ckw-grp"><span class="ckw-gl">' + ckw_esc(CKW_GROUP_NM[c.g] || '') + '</span>';
			gNow = c.g;
		}
		var on   = ckw.sel[c.key] ? ' on' : '';
		/* hit=0 = 최근 1년 안에 같은 키워드를 쓴 과거 건이 없다 = 이 병원에선 처음 나온 얘기.
		   정보로서는 의미가 있으니 보여 주되, 눌러도 빈 목록이 확정이므로 못 누르게 막는다. */
		var none = (ckw.state === 'done' && c.hit === 0);
		var dim  = none ? ' dim' : '';
		var tip  = c.kn + ' · ' + (ckw.state === 'done'
		         ? (c.hit > 0 ? '눌러서 이 키워드가 나온 과거 ' + c.hit + '건만 보기'
		                      : '최근 1년 과거 이력에 없음 (이 병원에선 처음 나온 키워드)')
		         : '분석 중');
		s += '<button type="button" class="ckw-chip k-' + c.k + on + dim + '" '
		  +  (none ? 'disabled ' : '')
		  +  'title="' + ckw_esc(tip) + '" onclick="ckw_toggle(' + i + ');">'
		  +    '<span class="ckw-ck">' + ckw_esc(c.kn) + '</span>'
		  +    '<span class="ckw-cv">' + ckw_esc(c.disp || c.label) + '</span>'
		  +    (c.hit > 0 ? '<span class="ckw-cn">' + c.hit + '</span>' : '')
		  +  '</button>';
	}
	if(gNow !== 0) s += '</div>';
	return s;
}

/* "왜 이게 위에 떴는지"를 한 줄로 설명한다. */
function ckw_reason(r){
	if(r.d.ref) return '문의 내용이 이 접수번호를 직접 언급했습니다';

	/* "어디서 + 무엇이" 가 상담원이 가장 먼저 확인하는 두 가지라 제일 앞에 둔다. */
	var head = [];
	if(r.d.pg && r.place) head.push('같은 ' + r.place);
	if(r.d.sy && r.sname) head.push(r.sname);
	if(head.length && r.hits.length) return head.join(' · ') + ' · ' + r.hits.slice(0, 3).join(', ');
	if(head.length) return head.join(' · ');
	if(r.hits.length) return '일치 : ' + r.hits.join(', ');

	var it = r.d.it;
	if(r.d.iq) return '같은 업무분류 · ' + ckw_nvl(it.inquiry_type_nm, '소분류 동일');
	if(r.d.sc) return '같은 시스템 · ' + ckw_nvl(it.service_cate_nm, '대분류 동일');
	return '최근 접수';
}

function ckw_listHtml(){
	if(ckw.state === 'nocust')  return '<div class="ckw-none">거래처 정보가 없어 연관 이력을 찾을 수 없습니다.</div>';
	if(ckw.state === 'loading') return '<div class="ckw-none"><span class="ckw-spin"></span>연관 이력을 찾는 중&hellip;</div>';
	if(ckw.state === 'error')   return '<div class="ckw-none err">' + ckw_esc(ckw.errMsg)
	                                 + ' <button type="button" class="ckw-retry" onclick="ckw_run(true);">다시 시도</button></div>';
	if(!ckw.ranked.length)      return '<div class="ckw-none">관련된 과거 상담이 없습니다. 아래 기간별 이력을 확인해 주세요.</div>';

	var top = ckw.ranked[0].raw, s = '', n = Math.min(CKW_TOP_N, ckw.ranked.length);
	for(var i=0; i<n; i++){
		var r  = ckw.ranked[i], it = r.d.it;
		var no = r.d.no;
		var txt = ckw_nvl(it.call_content,'');
		/* 막대는 1위 대비 상대값이다. 절대 점수를 %로 보여주면 근거 없는 확신을 준다. */
		var pct = r.d.ref ? 100 : Math.max(8, Math.round((r.raw / (top || 1)) * 100));

		s += '<button type="button" class="ckw-it' + (r.d.ref ? ' ref' : '') + '" '
		  +  'onclick="caws_pastOpen(\'' + ckw_esc(no) + '\',\'' + ckw_esc(ckw_nvl(it.cn_as_no,'')) + '\');">'
		  +    '<div class="ckw-ith">'
		  +      (r.d.ref ? '<span class="ckw-badge">직접 참조</span>' : '')
		  +      '<span class="ckw-idate">' + ckw_esc(caws_date(it.accept_dt)) + '</span>'
		  +      '<span class="st ' + asws_stClass(ckw_nvl(it.proc_status,'')) + '">'
		  +        ckw_esc(ckw_nvl(it.proc_status_nm,'-')) + '</span>'
		  +      '<span class="ckw-ino">' + ckw_esc(no) + '</span>'
		  +    '</div>'
		  +    '<div class="ckw-ibar"><i style="width:' + pct + '%"></i></div>'
		  +    '<div class="ckw-itxt">' + (txt ? ckw_esc(txt) : '<span class="none">요청내용 없음</span>') + '</div>'
		  +    '<div class="ckw-irs">' + ckw_esc(ckw_reason(r)) + '</div>'
		  +  '</button>';
	}
	if(ckw.ranked.length > n){
		s += '<div class="ckw-more">관련도 높은 순 상위 ' + n + '건입니다. 나머지는 아래 기간별 이력에서 확인할 수 있습니다.</div>';
	}
	return s;
}

function ckw_render(){
	var box = ckw_mount();
	if(!box) return;

	/* ★ 여기에 ckw.ranked.length 를 그대로 쓰면 안 된다.
	     ranked 는 "점수를 매겨 줄 세운 후보 전체"라 과거 200건 중 122건이 들어가기도 한다.
	     정작 화면에는 상위 5건만 나오는데 머리말만 "연관 이력 122건" 이라고 적히니,
	     상담원 입장에서는 관련 건이 122개나 있다는 말로 읽힌다. 실제로 이게 "내용이
	     이상하다" 로 보였다.
	     분류코드(문의유형/서비스분류)만 같아서 들어온 건은 세지 않고, 본문에 실제 근거가
	     있는 것만 센다. 컷 자체를 좁히는 것은 따로 재봤는데 정답을 놓쳐서(MRR 0.564 ->
	     0.464, 누락 154 -> 247건) 쓰면 안 된다. 세는 기준만 바꾼다. */
	var cnt = 0, ri;
	if(ckw.state === 'done'){
		for(ri=0; ri<ckw.ranked.length; ri++){
			var rr = ckw.ranked[ri];
			if(rr.d.ref || rr.hits.length || rr.d.pg || rr.d.sy) cnt++;
		}
	}
	var selOn = false;
	for(var k in ckw.sel){ if(ckw.sel[k]){ selOn = true; break; } }

	box.innerHTML =
		  '<div class="ckw-head">'
		+   '<span class="ckw-tit">문의 내용 키워드</span>'
		+   (selOn ? '<button type="button" class="ckw-clear" onclick="ckw_clear();">선택 해제</button>' : '')
		+ '</div>'
		+ '<div class="ckw-chips">' + ckw_chipsHtml() + '</div>'
		+ '<div class="ckw-head ckw-head2">'
		+   '<span class="ckw-tit">연관 이력</span>'
		+   '<span class="ckw-note">최근 1년 · 기간필터 무관</span>'
		+   '<span class="ckw-cnt">' + (ckw.state === 'done' ? cnt + '건' : '') + '</span>'
		+ '</div>'
		+ '<div class="ckw-list">' + ckw_listHtml() + '</div>';
}

