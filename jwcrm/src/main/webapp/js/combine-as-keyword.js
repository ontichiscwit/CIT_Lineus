/* 조사는 겹쳐서 붙는다. "재원중에서는" 은 '에서' + '는' 이라 한 번만 떼면
   "재원중에서" 가 남아 키워드 칩에 그대로 올라왔다. 그래서 더 못 뗄 때까지 반복한다.
   (최대 3회. 조사가 4개 이상 붙는 어절은 실데이터에 없었다) */
function ckw_josa(t){
	for(var n=0; n<3; n++){
		/* 2글자 이하는 건드리지 않는다. "이가", "에서" 처럼 통째로 조사 모양인 말이 있다. */
		if(t.length <= 2) break;
		var cut = false;
		for(var i=0; i<CKW_JOSA.length; i++){
			var j = CKW_JOSA[i];
			if(t.length <= j.length || t.substr(t.length - j.length) !== j) continue;
			t = t.substr(0, t.length - j.length);
			cut = true;
			break;
		}
		if(!cut) break;
	}
	return t;
}

