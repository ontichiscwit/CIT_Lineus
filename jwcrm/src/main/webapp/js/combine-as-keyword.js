/* yyyyMMdd -> Date. 형식이 아니면 null */
function ckw_toDate(v){
	var s = String(ckw_nvl(v,'')).replace(/[^0-9]/g,'');
	if(s.length < 8) return null;
	var d = new Date(Number(s.substr(0,4)), Number(s.substr(4,2)) - 1, Number(s.substr(6,2)));
	return isNaN(d.getTime()) ? null : d;
}
function ckw_gapDays(a, b){
	var da = ckw_toDate(a), db = ckw_toDate(b);
	if(!da || !db) return 9999;
	return Math.abs(da.getTime() - db.getTime()) / 86400000;
}

/* 응답 목록을 토큰화해서 ckw.docs 에 담고 점수를 매긴다. */
function ckw_rank(list){
	var me = ckw.asNo, i, k;
	var vo = caws.vo || {}, row = caws.row || {};
	var myDt = ckw_nvl(vo.accept_dt, ckw_nvl(row.accept_dt,''));
	var myIq = ckw_nvl(vo.inquiry_type, ckw_nvl(row.inquiry_type,''));
	var mySc = ckw_nvl(vo.service_cate, ckw_nvl(row.service_cate,''));

	ckw.qset = ckw_set(ckw_tok(ckw_scoreText()));
	ckw.docs = [];

	for(i=0; i<list.length; i++){
		var it = list[i];
		var no = ckw_nvl(it.as_no,'');
		if(no === '' || no === me) continue;					/* 지금 보고 있는 건 제외 */
		var body = ckw_nvl(it.call_content,'');
		var norm = ckw_strip(body);							/* 표기 정규화까지 끝난 본문 (한 번만) */
		var toks = ckw_tokOf(norm);
		ckw.docs.push({
			it   : it,
			no   : no,
			body : body,								/* 원문 (화면에 그대로 보여줄 것) */
			nb   : norm,								/* 이름 대조용 */
			nf   : ckw_flat(norm),						/* 띄어쓰기까지 지운 것 */
			toks : toks,
			set  : ckw_set(toks),
			sym  : ckw_set(ckw_sympsOf(norm)),					/* 무슨 문제였나 */
			iq   : (myIq !== '' && ckw_nvl(it.inquiry_type,'') === myIq) ? 1 : 0,
			sc   : (mySc !== '' && ckw_nvl(it.service_cate,'') === mySc) ? 1 : 0,
			rec  : Math.exp(-ckw_gapDays(myDt, ckw_nvl(it.accept_dt,'')) / CKW_W.half),
			pg   : 0,											/* 같은 프로그램/화면 (아래에서 채움) */
			sy   : 0,											/* 같은 증상 (아래에서 채움) */
			ref  : false
		});
	}

	/* 로컬 IDF : 후보 + 현재 문의를 코퍼스로 본다.
	   전사 IDF 와 성능 차이가 없음을 실측으로 확인했다(MRR 0.434 vs 0.431). */
	var M = ckw.docs.length + 1, df = {};
	for(i=0; i<ckw.docs.length; i++) for(k in ckw.docs[i].set) df[k] = (df[k] || 0) + 1;
	for(k in ckw.qset) df[k] = (df[k] || 0) + 1;
	ckw.idf = {};
	for(k in df) ckw.idf[k] = Math.log((M + 1) / (df[k] + 0.5));
	ckw.df = df;

	/* 본문이 직접 가리키는 접수번호는 후보 안에 있으면 "직접 참조"로 고정한다. */
	var refMap = ckw_set(ckw.refs || []);
	for(i=0; i<ckw.docs.length; i++) if(refMap[ckw.docs[i].no]) ckw.docs[i].ref = true;

	/* "어디서" — 이 병원이 실제 쓰는 프로그램/화면 사전을 후보에서 만들고, 본문을 훑는다. */
	ckw.dict = ckw_dictBuild(list);
	ckw_addPlaceChips();

	/* 같은 프로그램/화면인가, 같은 증상인가 */
	var myPlace = ckw.place || [], mySym = ckw.sym || [];
	for(i=0; i<ckw.docs.length; i++){
		var d = ckw.docs[i], j;
		for(j=0; j<myPlace.length; j++) if(ckw_placeIn(d.nb, d.nf, myPlace[j])){ d.pg = 1; break; }
		for(j=0; j<mySym.length; j++)   if(d.sym[mySym[j]]){ d.sy = 1; break; }
	}

	/* [AX Lab] 삭제 (2026-10-01 AX Lab): "그 외 키워드" 칩 줄을 내리지 않는다.
	   실제 화면에서 "칸이 1 · 이유 1 · 마취 1 · 수술실 2 · 업무 14" 처럼 떴다.
	   IDF 상위를 뽑는 것까지는 맞는데, 형태소 분석기 없이 뽑다 보니 한 어절이 쪼개진
	   조각("마취"/"수술실")이나 아무 데나 나오는 말("업무"/"이유")이 올라와서,
	   상담원이 이걸 보고 판단할 게 없었다. 어디서·무슨 문제 두 줄이 하는 일을
	   흐리기만 한다.
	   ★ 되돌리려면 아래 한 줄의 주석만 풀면 된다. ckw_addTermChips() 와
	     CKW_TERM_MAX, CKW_GROUP의 term:4 는 그대로 남겨 뒀다.
	   ★ 연관 이력 랭킹에는 영향이 없다. 점수는 칩이 아니라 본문 토큰 전체(ckw.qset)로
	     매기기 때문이다(ckw_rescore 참고). 바뀌는 건 "눌러서 거르는" 칩이 줄어드는 것뿐.
	ckw_addTermChips();
	*/
	ckw_rescore();
}

/* 구조화 칩이 이미 쓰는 토큰 집합.
   ↓ 아래 둘도 2026-10-01 현재 호출부 없음 ("그 외 키워드" 칩 전용). 되살릴 때를 위해 남겨 둔다. */
function ckw_structToks(){
	var m = {}, i, j;
	for(i=0; i<ckw.chips.length; i++){
		if(ckw.chips[i].k === 'term') continue;
		for(j=0; j<ckw.chips[i].toks.length; j++) m[ckw.chips[i].toks[j]] = 1;
	}
	return m;
}

function ckw_addTermChips(){
	var used = ckw_structToks(), cand = [], t;
	/* 기존 term 칩 제거(재계산) */
	var keep = [];
	for(var i=0; i<ckw.chips.length; i++) if(ckw.chips[i].k !== 'term') keep.push(ckw.chips[i]);
	ckw.chips = keep;

	for(t in ckw.qset){
		if(used[t]) continue;
		cand.push({ t:t, idf:(ckw.idf[t] || 0), hit:((ckw.df[t] || 1) - 1),
		            pn:(/[A-Za-z0-9]/.test(t) ? 1 : 0) });
	}
	/* 희소한(=이 문의를 특정짓는) 키워드가 먼저다.
	   처음엔 "과거 이력에 있는 것"을 먼저 보여줬는데, 과거에 많이 나온 단어는 정의상
	   흔한 단어라서 "없는 7" "되는 6" 같은 게 맨 앞에 오고 정작 SMSLive 는 밀렸다.
	   과거에 없다는 것(hit=0)도 "이 병원에선 처음 나온 얘기"라는 정보라서, 숨기지 말고
	   흐리게(dim) 표시만 한다.
	   동점이면 영문·숫자가 섞인 쪽(SMSLive, CITEMR 같은 고유명사)을 올린다. */
	cand.sort(function(a, b){
		if(b.idf !== a.idf) return b.idf - a.idf;
		if(b.pn  !== a.pn ) return b.pn  - a.pn;
		if(b.hit !== a.hit) return b.hit - a.hit;
		return b.t.length - a.t.length;
	});
	for(var n=0; n<cand.length && n<CKW_TERM_MAX; n++){
		var c = ckw_chip('term', '키워드', cand[n].t, [cand[n].t]);
		c.hit  = cand[n].hit;
		/* 맞춰 보는 건 잘린 토큰 그대로 두고, 화면에 쓸 글자만 원문에서 되찾는다.
		   (검사결 -> 검사결과, 정형외 -> 정형외과) key 는 label 로 만드니 건드리지 않는다. */
		c.disp = ckw_surface(cand[n].t);
		ckw.chips.push(c);
	}
}

/* 선택된 칩이 있으면 그 토큰만으로, 없으면 본문 전체 토큰으로 점수를 다시 매긴다. */
function ckw_rescore(){
	var i, j, k;

	/* 선택된 칩들을 모은다. 점수용 토큰 집합은 그 칩들의 토큰 합집합. */
	var selChips = [], sel = {};
	for(i=0; i<ckw.chips.length; i++){
		if(!ckw.sel[ckw.chips[i].key]) continue;
		selChips.push(ckw.chips[i]);
		for(j=0; j<ckw.chips[i].toks.length; j++) sel[ckw.chips[i].toks[j]] = 1;
	}
	var useSel = selChips.length > 0;
	var qs = useSel ? sel : (ckw.qset || {});
	var qn = 0; for(k in qs) qn++;

	/* 칩별 과거 이력 적중 수 초기화 */
	for(i=0; i<ckw.chips.length; i++) ckw.chips[i].hit = 0;

	var out = [];
	for(i=0; i<ckw.docs.length; i++){
		var d = ckw.docs[i];
		var inter = [], wgt = 0, cn = d.toks.length;
		for(k in qs) if(d.set[k]){ inter.push(k); wgt += (ckw.idf[k] || 0); }

		var overlap = wgt / Math.sqrt((qn * cn) + 1);
		var score   = overlap
		            + CKW_W.rec * d.rec
		            + CKW_W.iq  * d.iq
		            + CKW_W.sc  * d.sc
		            + CKW_W.pg  * d.pg
		            + CKW_W.sy  * d.sy;

		/* 칩 적중 수 집계 (선택 여부와 무관하게 "이 키워드가 과거에 있었나"를 보여주기 위함) */
		for(j=0; j<ckw.chips.length; j++) if(ckw_chipHits(ckw.chips[j], d)) ckw.chips[j].hit++;

		if(useSel){
			/* 선택 모드: 선택한 칩 중 하나라도 "칩 숫자와 같은 기준"으로 걸려야 남는다.
			   칩 여러 개를 고르면 OR 로 합쳐진다(= 숫자들의 합집합).
			   ★ 아래 "근거 없음" 컷을 여기서 타면 안 된다. 증상 칩은 토큰이 없어서
			     inter 가 항상 비고, 그 컷에 걸려 "안됨/실패 4" 를 눌렀는데 1건만
			     나오는 일이 생겼다. 선택 모드에서는 "고른 칩에 걸린다" 자체가 근거다. */
			if(!d.ref){
				var ok = false;
				for(j=0; j<selChips.length; j++) if(ckw_chipHits(selChips[j], d)){ ok = true; break; }
				if(!ok) continue;
			}
		}
		/* 근거를 한 줄도 못 대는 건은 보여주지 않는다.
		   ("왜 위에 떴는지" 설명 못 하는 추천은 상담원이 신뢰하지 않는다) */
		else if(!d.ref && inter.length === 0 && d.iq === 0 && d.sc === 0 && d.pg === 0) continue;

		/* 화면 표시용으로 IDF 높은 순 상위 몇 개만 남긴다 */
		inter.sort(function(a, b){ return (ckw.idf[b] || 0) - (ckw.idf[a] || 0); });

		/* 설명줄에 쓸 "어디서/무엇이" 를 같이 담는다 */
		var pnm = '', snm = '';
		if(d.pg) for(j=0; j<(ckw.place||[]).length; j++) if(ckw_placeIn(d.nb, d.nf, ckw.place[j])){ pnm = ckw.place[j]; break; }
		if(d.sy) for(j=0; j<(ckw.sym||[]).length; j++)   if(d.sym[ckw.sym[j]]){ snm = ckw_sympNm(ckw.sym[j]); break; }

		out.push({ d:d, score:(d.ref ? 999 + d.rec : score), raw:score,
		           hits:inter.slice(0, 5), place:pnm, sname:snm });
	}

	out.sort(function(a, b){
		if(b.score !== a.score) return b.score - a.score;
		return String(b.d.no).localeCompare(String(a.d.no));	/* 동점이면 최신 접수번호 */
	});
	ckw.ranked = out;
}

