-- 배경 : 기존에는 동일한 기간 리터럴이 01~05 다섯 파일에 복붙돼 있었다.
--        한쪽만 고치면 cases.csv 와 answers.csv 의 대상 건이 어긋나는데,
--        build_dataset.py 는 cases.csv 기준으로 순회하며
--        answers_by_case.get(as_no, 빈DataFrame) 으로 스레드를 찾기 때문에
--        누락된 건이 오류 없이 thread=[] (= 무응답) 으로 집계된다.
--        즉 조용히 통계가 틀어지므로, 기간은 반드시 단일 출처로 관리한다.
--
-- 사용 : 01~05 각 SQL 상단의  @@00_params.sql  이 이 파일을 불러온다.
--        - SQL Developer : F5(스크립트 실행)로 파일 전체를 실행할 것.
--        - 블록 단위(Ctrl+Enter) 실행 시에는 이 파일을 먼저 한 번 실행해두면
--          같은 세션(워크시트) 동안 DEFINE 값이 계속 유지된다.
--        - 값을 바꿀 때는 아래 두 줄만 수정하면 01~05 전부에 반영된다.
--
-- 형식 : ACCEPT_DT 가 VARCHAR2 이므로 YYYYMMDD 8자리 문자열로 비교한다.
--        아래 DEFINE 의 작은따옴표는 값의 구분자이며 치환될 때 제거된다.
--        (즉 치환 결과는 20250101 이므로, 사용처에서 다시 따옴표로 감싸야 한다)
--        DEFINE 줄 뒤에 같은 줄로 주석을 달면 주석까지 값에 들어가므로 금지.
--        주석 안에서는 앰퍼샌드 + 변수명 표기를 쓰지 말 것.
--        SQL*Plus / SQL Developer 는 주석도 치환 대상으로 스캔하기 때문에
--        DEFINE 보다 윗줄에 그 표기가 있으면 값을 입력하라는 창이 뜬다.
